-- Payments received on issued invoices (#44). Their sum is kept in invoices.amount_paid by the same transaction.
-- A payment is never edited: a mistake is corrected by deleting it and recording the right one.
CREATE TABLE payments (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id     BIGINT                      NOT NULL,
    invoice_id   BIGINT                      NOT NULL,
    amount       NUMERIC(14, 2)              NOT NULL,
    payment_date DATE                        NOT NULL,
    method       VARCHAR(20)                 NOT NULL,
    reference    VARCHAR(100),
    note         VARCHAR(500),
    created_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_payments_owner FOREIGN KEY (owner_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_payments_invoice FOREIGN KEY (invoice_id) REFERENCES invoices (id) ON DELETE CASCADE,
    CONSTRAINT ck_payments_amount CHECK (amount > 0),
    CONSTRAINT ck_payments_method
        CHECK (method IN ('BANK_TRANSFER', 'CARD', 'CHEQUE', 'CASH', 'DIRECT_DEBIT', 'OTHER'))
);

CREATE INDEX idx_payments_owner_id ON payments (owner_id);
CREATE INDEX idx_payments_invoice_id ON payments (invoice_id);
