-- Append-only log of what admins do to accounts (#46, ADR 0010). admin_id is NULL for a promotion from
-- ADMIN_EMAILS. Rows are never updated; the application maps them to an immutable entity.
CREATE TABLE admin_actions (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id       BIGINT,
    action         VARCHAR(40)              NOT NULL,
    target_user_id BIGINT                   NOT NULL,
    details        VARCHAR(255),
    created_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_admin_actions_admin FOREIGN KEY (admin_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT fk_admin_actions_target FOREIGN KEY (target_user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_admin_actions_action CHECK (action IN
        ('ROLE_CHANGED', 'ACCOUNT_SUSPENDED', 'ACCOUNT_REACTIVATED', 'PROMOTED_FROM_CONFIG'))
);

CREATE INDEX idx_admin_actions_created_at ON admin_actions (created_at DESC, id DESC);
