-- Invoices of a user. The customer's billing details are copied onto the invoice: refreshed while it is a draft,
-- frozen once it is issued, so that an issued invoice never changes when the customer is edited or deleted.
CREATE TABLE invoices (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id             BIGINT                   NOT NULL,
    number               VARCHAR(20),
    status               VARCHAR(10)              NOT NULL,
    customer_id          BIGINT,
    customer_name        VARCHAR(255),
    customer_email       VARCHAR(255),
    customer_street      VARCHAR(255),
    customer_postal_code VARCHAR(255),
    customer_city        VARCHAR(255),
    customer_country     VARCHAR(255),
    customer_siret       VARCHAR(14),
    customer_vat_number  VARCHAR(255),
    payment_terms        VARCHAR(20)              NOT NULL,
    issue_date           DATE,
    due_date             DATE,
    notes                VARCHAR(2000),
    subtotal             NUMERIC(14, 2)           NOT NULL,
    vat_total            NUMERIC(14, 2)           NOT NULL,
    total                NUMERIC(14, 2)           NOT NULL,
    issued_at            TIMESTAMP(6) WITH TIME ZONE,
    cancelled_at         TIMESTAMP(6) WITH TIME ZONE,
    created_at           TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at           TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_invoices_owner FOREIGN KEY (owner_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_invoices_customer FOREIGN KEY (customer_id) REFERENCES customers (id) ON DELETE SET NULL,
    CONSTRAINT uq_invoices_owner_number UNIQUE (owner_id, number),
    CONSTRAINT ck_invoices_status CHECK (status IN ('DRAFT', 'ISSUED', 'CANCELLED')),
    CONSTRAINT ck_invoices_payment_terms
        CHECK (payment_terms IN ('ON_RECEIPT', 'NET_15', 'NET_30', 'NET_45', 'NET_60', 'END_OF_MONTH_45')),
    -- Only drafts have no number and no dates
    CONSTRAINT ck_invoices_issued
        CHECK (status = 'DRAFT' OR (number IS NOT NULL AND issue_date IS NOT NULL AND due_date IS NOT NULL))
);

CREATE INDEX idx_invoices_owner_id ON invoices (owner_id);
CREATE INDEX idx_invoices_customer_id ON invoices (customer_id);

CREATE TABLE invoice_lines (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id  BIGINT         NOT NULL,
    sort_order  INTEGER        NOT NULL,
    product_id  BIGINT,
    type        VARCHAR(10)    NOT NULL,
    label       VARCHAR(255)   NOT NULL,
    details     VARCHAR(1000),
    quantity    NUMERIC(12, 3) NOT NULL,
    unit        VARCHAR(10)    NOT NULL,
    unit_price  NUMERIC(12, 2) NOT NULL,
    vat_rate    NUMERIC(4, 2)  NOT NULL,
    line_total  NUMERIC(14, 2) NOT NULL,
    CONSTRAINT fk_invoice_lines_invoice FOREIGN KEY (invoice_id) REFERENCES invoices (id) ON DELETE CASCADE,
    CONSTRAINT fk_invoice_lines_product FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE SET NULL,
    CONSTRAINT ck_invoice_lines_type CHECK (type IN ('GOODS', 'SERVICE')),
    CONSTRAINT ck_invoice_lines_quantity CHECK (quantity > 0),
    CONSTRAINT ck_invoice_lines_unit_price CHECK (unit_price >= 0),
    CONSTRAINT ck_invoice_lines_vat_rate CHECK (vat_rate IN (20.00, 10.00, 5.50, 2.10, 0.00)),
    CONSTRAINT ck_invoice_lines_unit CHECK (unit IN ('UNIT', 'HOUR', 'DAY', 'MONTH', 'KILOGRAM', 'METER'))
);

CREATE INDEX idx_invoice_lines_invoice_id ON invoice_lines (invoice_id);
CREATE INDEX idx_invoice_lines_product_id ON invoice_lines (product_id);

-- Last number given to an issued invoice, per owner and year. Its row is locked by the issuing transaction,
-- so numbers are consecutive and never reused, even when two invoices are issued at the same time.
CREATE TABLE invoice_number_sequences (
    owner_id    BIGINT  NOT NULL,
    fiscal_year INTEGER NOT NULL,
    last_value  INTEGER NOT NULL,
    CONSTRAINT pk_invoice_number_sequences PRIMARY KEY (owner_id, fiscal_year),
    CONSTRAINT fk_invoice_number_sequences_owner FOREIGN KEY (owner_id) REFERENCES users (id) ON DELETE CASCADE
);
