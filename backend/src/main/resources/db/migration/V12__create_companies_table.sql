-- The seller: one company profile per user (#48). Its details are copied onto an invoice when it is issued,
-- so editing the profile never changes an issued invoice.
CREATE TABLE companies (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id      BIGINT                   NOT NULL,
    legal_name    VARCHAR(255)             NOT NULL,
    trade_name    VARCHAR(255),
    legal_form    VARCHAR(10)              NOT NULL,
    share_capital NUMERIC(14, 2),
    street        VARCHAR(255)             NOT NULL,
    postal_code   VARCHAR(10)              NOT NULL,
    city          VARCHAR(255)             NOT NULL,
    country       VARCHAR(255)             NOT NULL,
    siret         VARCHAR(14)              NOT NULL,
    vat_number    VARCHAR(20),
    vat_regime    VARCHAR(10)              NOT NULL,
    registration  VARCHAR(120),
    email         VARCHAR(255),
    phone         VARCHAR(30),
    iban          VARCHAR(34),
    bic           VARCHAR(11),
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_companies_owner FOREIGN KEY (owner_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT uk_companies_owner UNIQUE (owner_id),
    CONSTRAINT ck_companies_legal_form CHECK (legal_form IN
        ('EI', 'EI_MICRO', 'EURL', 'SARL', 'SASU', 'SAS', 'SA', 'SNC', 'OTHER')),
    CONSTRAINT ck_companies_share_capital CHECK (share_capital IS NULL OR share_capital >= 0),
    CONSTRAINT ck_companies_vat_regime CHECK (vat_regime IN ('STANDARD', 'FRANCHISE'))
);
