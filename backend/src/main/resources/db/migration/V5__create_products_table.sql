-- Catalogue of goods and services sold by a user. Prices exclude VAT; the VAT rate is one of the French rates.
CREATE TABLE products (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id    BIGINT                   NOT NULL,
    type        VARCHAR(10)              NOT NULL,
    name        VARCHAR(255)             NOT NULL,
    description VARCHAR(1000),
    unit_price  NUMERIC(12, 2)           NOT NULL,
    vat_rate    NUMERIC(4, 2)            NOT NULL,
    unit        VARCHAR(10)              NOT NULL,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_products_owner FOREIGN KEY (owner_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_products_type CHECK (type IN ('GOODS', 'SERVICE')),
    CONSTRAINT ck_products_unit_price CHECK (unit_price >= 0),
    CONSTRAINT ck_products_vat_rate CHECK (vat_rate IN (20.00, 10.00, 5.50, 2.10, 0.00)),
    CONSTRAINT ck_products_unit CHECK (unit IN ('UNIT', 'HOUR', 'DAY', 'MONTH', 'KILOGRAM', 'METER'))
);

CREATE INDEX idx_products_owner_id ON products (owner_id);
